// The first authoring choice is correct. Runtime shuffling uses stable IDs, never positions.
function q(
  id: string,
  difficulty: Difficulty,
  category: string,
  question: string,
  options: [string, string, string, string],
  explanation: string,
  source: keyof typeof sources,
): Question {
  return {
    id,
    difficulty,
    category,
    question,
    choices: options.map((text, i) => ({
      id: `${id}-${i}`,
      text,
    })) as unknown as Question["choices"],
    correctAnswer: `${id}-0`,
    explanation,
    sourceUrl: sources[source],
    reviewedAt: "2026-09-27",
  };
}

